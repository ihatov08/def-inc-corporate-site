// 取引実績のある企業。/works の上部にロゴ一覧として表示します。
//
// ロゴ画像は public/images/clients/ に置き、logo に '/images/clients/xxx.svg' の形で指定します。
// logo を省略すると社名テキストのプレート表示になるので、画像が用意できるまではそのままで問題ありません。
//
// 注意: 他社のロゴ・社名の掲載には、原則として取引先からの許諾が必要です。
// 許諾が取れていない取引先はこの配列に追加せず、実績カード側で「都内の美容サロン様」のように
// 抽象化して掲載してください。
export type Client = {
  /** 表示する社名 */
  name: string;
  /** ロゴ画像のパス（任意。未指定なら社名テキストで表示） */
  logo?: string;
  /** 企業サイトのURL（任意。指定するとロゴがリンクになる） */
  url?: string;
  /** 関連する実績ページのスラッグ（任意。/works/<slug> へのリンクになる。url より優先） */
  work?: string;
};

